// Builds js/templates.js (default glyph templates) from the example photo with known values.
// Needs sharp:  npm i --no-save sharp  &&  node tools/build-templates.js
const fs = require("fs"), path = require("path"), sharp = require("sharp");
const R = p => path.join(__dirname, "..", p);
require(R("js/cells.js")); require(R("js/digits.js"));
const PHOTO = R("test/beispiel.jpg");
const RECT = {x:.32, y:.485, w:.507, h:.2};       // frame around Card 0 / Card 1 in the example photo
const VALUES = [["A37D0220022","A37D0220055"],["89430945038",""],["89430945097",""],
                ["B0BF0868946","B0BF0868871"],["B0BF0869065","B0BF0868913"],["B0BF0868894","B0BF0868908"]];
(async () => {
  const meta = await sharp(PHOTO).metadata();
  const sums = {};
  // several slightly different frames give more varied samples
  for(const [dx,dy,dw,dh] of [[0,0,0,0],[-.015,-.008,.03,.016],[-.03,-.01,.06,.02],[.005,.005,-.01,-.01],[-.01,.003,.02,-.006]]){
    const crop = {left:Math.round((RECT.x+dx)*meta.width), top:Math.round((RECT.y+dy)*meta.height), width:Math.round((RECT.w+dw)*meta.width), height:Math.round((RECT.h+dh)*meta.height)};
    const cr = await sharp(PHOTO).extract(crop).toBuffer();
    const {data, info} = await sharp(cr).resize({width:Math.min(1600, crop.width)}).grayscale().raw().toBuffer({resolveWithObject:true});
    const res = CellFinder.splitTable(data, info.width, info.height);
    if(res.rows.length !== VALUES.length){ console.log("skip frame", dx, dy, "-", res.rows.length, "rows"); continue; }
    res.rows.forEach((r,i) => r.cells.forEach((c,ci) => { if(!c || !VALUES[i][ci]) return;
      Digits.addSamples(sums, Digits.glyphs(data, info.width, info.height, {x0:c.x0,x1:c.x1,y0:r.y0,y1:r.y1}, VALUES[i][ci])); }));
  }
  const enc = {}; for(const ch in sums) enc[ch] = {n: sums[ch].n, s: sums[ch].s.map(v => Math.round(v*1000)/1000)};
  fs.writeFileSync(R("js/templates.js"), "// generated by tools/build-templates.js from test/beispiel.jpg\n(typeof window!==\"undefined\"?window:globalThis).CARDQR_TEMPLATES = " + JSON.stringify(enc) + ";\n");
  console.log("templates:", Object.keys(enc).sort().map(c => c + "×" + enc[c].n).join(" "));
})();
